from django.contrib.auth import get_user_model
from rest_framework import status
from rest_framework.test import APITestCase

from .models import Category

User = get_user_model()


class CategoryModelTests(APITestCase):
    def test_slug_autogenerated_from_name(self):
        category = Category.objects.create(name="Технологии")
        self.assertEqual(category.slug, "технологии")
        self.assertTrue(category.slug)

    def test_str_returns_name(self):
        category = Category.objects.create(name="Путешествия")
        self.assertEqual(str(category), "Путешествия")


class CategoryAPITests(APITestCase):
    def setUp(self):
        self.admin = User.objects.create_user(
            username="admin",
            email="admin@test.com",
            password="pass12345",
            role="admin",
        )
        self.reader = User.objects.create_user(
            username="reader",
            email="reader@test.com",
            password="pass12345",
            role="reader",
        )
        self.category = Category.objects.create(name="Наука")

    def test_anyone_can_list_categories(self):
        response = self.client.get("/api/categories/")
        self.assertEqual(response.status_code, status.HTTP_200_OK)

    def test_reader_cannot_create_category(self):
        self.client.force_authenticate(self.reader)
        response = self.client.post("/api/categories/", {"name": "Спорт"})
        self.assertEqual(response.status_code, status.HTTP_403_FORBIDDEN)

    def test_admin_can_create_category(self):
        self.client.force_authenticate(self.admin)
        response = self.client.post("/api/categories/", {"name": "Спорт"})
        self.assertEqual(response.status_code, status.HTTP_201_CREATED)

    def test_category_cannot_be_own_parent(self):
        self.client.force_authenticate(self.admin)
        response = self.client.patch(
            f"/api/categories/{self.category.slug}/",
            {"parent": self.category.id},
        )
        self.assertEqual(response.status_code, status.HTTP_400_BAD_REQUEST)

    def test_category_cannot_create_cycle(self):
        parent = Category.objects.create(name="Родитель")
        child = Category.objects.create(name="Ребёнок", parent=parent)

        self.client.force_authenticate(self.admin)
        response = self.client.patch(
            f"/api/categories/{parent.slug}/",
            {"parent": child.id},
        )
        self.assertEqual(response.status_code, status.HTTP_400_BAD_REQUEST)