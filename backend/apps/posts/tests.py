class PostModelTests(APITestCase):
    def setUp(self):
        self.author = User.objects.create_user(
            username="author1",
            email="author1@test.com",
            password="pass12345",
            role="author",
        )

    def test_slug_autogenerated_from_title(self):
        post = Post.objects.create(
            author=self.author, title="Привет мир", content="Текст"
        )
        self.assertTrue(post.slug)
        self.assertEqual(post.slug, "привет-мир")

    def test_duplicate_titles_get_unique_slugs(self):
        post1 = Post.objects.create(
            author=self.author, title="Тест", content="Текст 1"
        )
        post2 = Post.objects.create(
            author=self.author, title="Тест", content="Текст 2"
        )
        self.assertNotEqual(post1.slug, post2.slug)

    def test_str_returns_title(self):
        post = Post.objects.create(
            author=self.author, title="Заголовок", content="Текст"
        )
        self.assertEqual(str(post), "Заголовок")

    def test_is_published_property(self):
        post = Post.objects.create(
            author=self.author, title="Пост", content="Текст"
        )
        self.assertFalse(post.is_published)

        post.status = Post.Status.PUBLISHED
        post.save()
        self.assertTrue(post.is_published)

    def test_reading_time(self):
        post = Post.objects.create(
            author=self.author,
            title="Пост",
            content=" ".join(["слово"] * 100),
        )
        self.assertEqual(post.reading_time, 1)

    def test_get_absolute_url(self):
        post = Post.objects.create(
            author=self.author, title="Мой пост", content="Текст"
        )
        self.assertEqual(post.get_absolute_url(), f"/posts/{post.slug}/")

    def test_publish_method(self):
        post = Post.objects.create(
            author=self.author, title="Черновик", content="Текст"
        )
        post.publish()
        post.refresh_from_db()
        self.assertEqual(post.status, Post.Status.PUBLISHED)
        self.assertIsNotNone(post.published_at)

    def test_archive_method(self):
        post = Post.objects.create(
            author=self.author, title="Пост", content="Текст"
        )
        post.archive()
        post.refresh_from_db()
        self.assertEqual(post.status, Post.Status.ARCHIVED)

    def test_draft_method(self):
        post = Post.objects.create(
            author=self.author,
            title="Пост",
            content="Текст",
            status=Post.Status.PUBLISHED,
        )
        post.draft()
        post.refresh_from_db()
        self.assertEqual(post.status, Post.Status.DRAFT)

    def test_increment_views(self):
        post = Post.objects.create(
            author=self.author, title="Пост", content="Текст"
        )
        post.increment_views()
        post.refresh_from_db()
        self.assertEqual(post.views_count, 1)

    def test_get_published_classmethod(self):
        Post.objects.create(
            author=self.author, title="Черновик", content="Текст"
        )
        Post.objects.create(
            author=self.author,
            title="Опубликован",
            content="Текст",
            status=Post.Status.PUBLISHED,
        )
        self.assertEqual(Post.get_published().count(), 1)

    def test_get_drafts_classmethod(self):
        Post.objects.create(
            author=self.author, title="Черновик", content="Текст"
        )
        Post.objects.create(
            author=self.author,
            title="Опубликован",
            content="Текст",
            status=Post.Status.PUBLISHED,
        )
        self.assertEqual(Post.get_drafts().count(), 1)

class PostAPITests(APITestCase):
    def setUp(self):
        self.author = User.objects.create_user(
            username="author2",
            email="author2@test.com",
            password="pass12345",
            role="author",
        )
        self.reader = User.objects.create_user(
            username="reader",
            email="reader@test.com",
            password="pass12345",
            role="reader",
        )
        self.admin = User.objects.create_user(
            username="admin",
            email="admin@test.com",
            password="pass12345",
            role="admin",
        )
        self.category = Category.objects.create(name="Наука")
        self.tag = Tag.objects.create(name="python")

        self.post = Post.objects.create(
            author=self.author,
            title="Опубликованный пост",
            content="Содержимое поста",
            category=self.category,
            status=Post.Status.PUBLISHED,
        )
        self.post.tags.add(self.tag)

        self.post_url = f"/api/posts/{self.post.slug}/"
        self.posts_url = "/api/posts/"

    def test_anonymous_sees_only_published(self):
        Post.objects.create(
            author=self.author, title="Черновик", content="Текст"
        )
        response = self.client.get(self.posts_url)
        self.assertEqual(len(response.data["results"]), 1)

    def test_authenticated_sees_all(self):
        Post.objects.create(
            author=self.author, title="Черновик", content="Текст"
        )
        self.client.force_authenticate(self.author)
        response = self.client.get(self.posts_url)
        self.assertEqual(len(response.data["results"]), 2)

    def test_reader_cannot_create_post(self):
        self.client.force_authenticate(self.reader)
        response = self.client.post(self.posts_url, {
            "title": "Попытка", "content": "Текст"
        })
        self.assertEqual(response.status_code, status.HTTP_403_FORBIDDEN)

    def test_author_can_create_post(self):
        self.client.force_authenticate(self.author)
        response = self.client.post(self.posts_url, {
            "title": "Новый пост", "content": "Текст поста"
        })
        self.assertEqual(response.status_code, status.HTTP_201_CREATED)

    def test_admin_can_create_post(self):
        self.client.force_authenticate(self.admin)
        response = self.client.post(self.posts_url, {
            "title": "Пост админа", "content": "Текст"
        })
        self.assertEqual(response.status_code, status.HTTP_201_CREATED)

    def test_author_can_edit_own_post(self):
        self.client.force_authenticate(self.author)
        response = self.client.patch(self.post_url, {"title": "Новый заголовок"})
        self.assertEqual(response.status_code, status.HTTP_200_OK)

    def test_reader_cannot_edit_post(self):
        self.client.force_authenticate(self.reader)
        response = self.client.patch(self.post_url, {"title": "Взлом"})
        self.assertEqual(response.status_code, status.HTTP_403_FORBIDDEN)

    def test_admin_can_edit_any_post(self):
        self.client.force_authenticate(self.admin)
        response = self.client.patch(self.post_url, {"title": "Админ"})
        self.assertEqual(response.status_code, status.HTTP_200_OK)

    def test_author_can_delete_own_post(self):
        self.client.force_authenticate(self.author)
        response = self.client.delete(self.post_url)
        self.assertEqual(response.status_code, status.HTTP_204_NO_CONTENT)

    def test_reader_cannot_delete_post(self):
        self.client.force_authenticate(self.reader)
        response = self.client.delete(self.post_url)
        self.assertEqual(response.status_code, status.HTTP_403_FORBIDDEN)

    def test_retrieve_increments_views(self):
        self.client.get(self.post_url)
        self.post.refresh_from_db()
        self.assertEqual(self.post.views_count, 1)

    def test_author_view_does_not_increment(self):
        self.client.force_authenticate(self.author)
        self.client.get(self.post_url)
        self.post.refresh_from_db()
        self.assertEqual(self.post.views_count, 0)

    def test_like_post(self):
        self.client.force_authenticate(self.reader)
        response = self.client.post(f"/api/posts/{self.post.slug}/like/")
        self.assertEqual(response.status_code, status.HTTP_201_CREATED)

    def test_cannot_like_own_post(self):
        self.client.force_authenticate(self.author)
        response = self.client.post(f"/api/posts/{self.post.slug}/like/")
        self.assertEqual(response.status_code, status.HTTP_400_BAD_REQUEST)

    def test_duplicate_like(self):
        self.client.force_authenticate(self.reader)
        self.client.post(f"/api/posts/{self.post.slug}/like/")
        response = self.client.post(f"/api/posts/{self.post.slug}/like/")
        self.assertEqual(response.status_code, status.HTTP_400_BAD_REQUEST)

    def test_unlike_post(self):
        self.client.force_authenticate(self.reader)
        self.client.post(f"/api/posts/{self.post.slug}/like/")
        response = self.client.post(f"/api/posts/{self.post.slug}/unlike/")
        self.assertEqual(response.status_code, status.HTTP_204_NO_CONTENT)

    def test_publish_post(self):
        draft = Post.objects.create(
            author=self.author, title="Черновик", content="Текст"
        )
        self.client.force_authenticate(self.author)
        response = self.client.post(f"/api/posts/{draft.slug}/publish/")
        self.assertEqual(response.status_code, status.HTTP_200_OK)
        draft.refresh_from_db()
        self.assertEqual(draft.status, Post.Status.PUBLISHED)

    def test_archive_post(self):
        self.client.force_authenticate(self.author)
        response = self.client.post(f"/api/posts/{self.post.slug}/archive/")
        self.assertEqual(response.status_code, status.HTTP_200_OK)
        self.post.refresh_from_db()
        self.assertEqual(self.post.status, Post.Status.ARCHIVED)

    def test_my_posts(self):
        self.client.force_authenticate(self.author)
        response = self.client.get("/api/posts/my_posts/")
        self.assertEqual(response.status_code, status.HTTP_200_OK)

    def test_filter_by_category(self):
        self.client.force_authenticate(self.author)
        response = self.client.get(f"{self.posts_url}?category={self.category.slug}")
        self.assertEqual(len(response.data["results"]), 1)

    def test_filter_by_tag(self):
        self.client.force_authenticate(self.author)
        response = self.client.get(f"{self.posts_url}?tag={self.tag.slug}")
        self.assertEqual(len(response.data["results"]), 1)

    def test_search_posts(self):
        self.client.force_authenticate(self.author)
        response = self.client.get(f"{self.posts_url}?search=Опубликованный")
        self.assertEqual(len(response.data["results"]), 1)

class PostAdminTests(APITestCase):

    def setUp(self):
        self.site = AdminSite()
        self.admin = PostAdmin(Post, self.site)
        self.factory = RequestFactory()

        self.author = User.objects.create_user(
            username="admin_author",
            email="admin_author@test.com",
            password="pass12345",
            role="author",
        )
        self.superuser = User.objects.create_user(
            username="superuser",
            email="superuser@test.com",
            password="pass12345",
            role="admin",
            is_staff=True,
            is_superuser=True,
        )
        self.category = Category.objects.create(name="Наука")
        self.post = Post.objects.create(
            author=self.author,
            title="Тестовый пост с очень длинным заголовком для проверки обрезки",
            content="Содержимое поста",
            category=self.category,
            status=Post.Status.PUBLISHED,
        )

    def test_title_preview_short(self):
        post = Post.objects.create(
            author=self.author, title="Короткий", content="Текст"
        )
        html = self.admin.title_preview(post)
        self.assertEqual(html, "Короткий")

    def test_title_preview_long(self):
        html = self.admin.title_preview(self.post)
        self.assertIn("...", html)
        self.assertLessEqual(len(html), 53)

    def test_author_link(self):
        html = self.admin.author_link(self.post)
        self.assertIn(self.author.username, html)
        self.assertIn(str(self.author.id), html)

    def test_category_link_with_category(self):
        html = self.admin.category_link(self.post)
        self.assertIn(self.category.name, html)
        self.assertIn(str(self.category.id), html)

    def test_category_link_without_category(self):
        post = Post.objects.create(
            author=self.author, title="Пост", content="Текст"
        )
        html = self.admin.category_link(post)
        self.assertEqual(html, "-")

    def test_status_colored_published(self):
        html = self.admin.status_colored(self.post)
        self.assertIn("Опубликован", html)
        self.assertIn("#10b981", html)  # Новый зеленый цвет

    def test_status_colored_draft(self):
        post = Post.objects.create(
            author=self.author, title="Пост", content="Текст"
        )
        html = self.admin.status_colored(post)
        self.assertIn("Черновик", html)
        self.assertIn("#f59e0b", html)  # Новый желтый цвет

    def test_status_colored_archived(self):
        post = Post.objects.create(
            author=self.author,
            title="Пост",
            content="Текст",
            status=Post.Status.ARCHIVED,
        )
        html = self.admin.status_colored(post)
        self.assertIn("В архиве", html)
        self.assertIn("#6b7280", html)  # Новый серый цвет

    def test_is_recent_true(self):
        self.assertTrue(self.admin.is_recent(self.post))

    def test_is_recent_false(self):
        post = Post.objects.create(
            author=self.author, title="Старый пост", content="Текст"
        )
        post.created_at = timezone.now() - timedelta(days=10)
        post.save()
        self.assertFalse(self.admin.is_recent(post))

    def test_cover_image_preview_without_image(self):
        html = self.admin.cover_image_preview(self.post)
        self.assertEqual(html, "")  # Новый код возвращает пустую строку

    def test_make_published_action(self):
        post = Post.objects.create(
            author=self.author, title="Черновик", content="Текст"
        )
        request = self.factory.post("/admin/posts/post/")
        request.user = self.superuser
        self.admin.message_user = lambda *args, **kwargs: None

        queryset = Post.objects.filter(id=post.id)
        self.admin.make_published(request, queryset)

        post.refresh_from_db()
        self.assertEqual(post.status, Post.Status.PUBLISHED)

    def test_make_draft_action(self):
        request = self.factory.post("/admin/posts/post/")
        request.user = self.superuser
        self.admin.message_user = lambda *args, **kwargs: None

        queryset = Post.objects.filter(id=self.post.id)
        self.admin.make_draft(request, queryset)

        self.post.refresh_from_db()
        self.assertEqual(self.post.status, Post.Status.DRAFT)

    def test_make_archived_action(self):
        request = self.factory.post("/admin/posts/post/")
        request.user = self.superuser
        self.admin.message_user = lambda *args, **kwargs: None

        queryset = Post.objects.filter(id=self.post.id)
        self.admin.make_archived(request, queryset)

        self.post.refresh_from_db()
        self.assertEqual(self.post.status, Post.Status.ARCHIVED)

    def test_reset_views_action(self):
        self.post.views_count = 100
        self.post.save()

        request = self.factory.post("/admin/posts/post/")
        request.user = self.superuser
        self.admin.message_user = lambda *args, **kwargs: None

        queryset = Post.objects.filter(id=self.post.id)
        self.admin.reset_views(request, queryset)

        self.post.refresh_from_db()
        self.assertEqual(self.post.views_count, 0)

    def test_save_model_sets_author(self):
        post = Post(
            title="Новый пост",
            content="Текст",
        )
        request = self.factory.post("/admin/posts/post/add/")
        request.user = self.superuser

        self.admin.save_model(request, post, form=None, change=False)
        self.assertEqual(post.author, self.superuser)

    def test_save_model_keeps_author_on_change(self):
        original_author = self.post.author
        request = self.factory.post("/admin/posts/post/1/change/")
        request.user = self.superuser

        self.admin.save_model(request, self.post, form=None, change=True)
        self.assertEqual(self.post.author, original_author)

    def test_get_readonly_fields_adds_author_on_change(self):
        request = self.factory.get("/admin/posts/post/1/change/")
        request.user = self.superuser

        readonly = self.admin.get_readonly_fields(request, obj=self.post)
        self.assertIn("author", readonly)

    def test_get_readonly_fields_without_obj(self):
        request = self.factory.get("/admin/posts/post/add/")
        request.user = self.superuser

        readonly = self.admin.get_readonly_fields(request, obj=None)
        self.assertNotIn("author", readonly)

    def test_has_delete_permission_superuser(self):
        request = self.factory.get("/admin/posts/post/")
        request.user = self.superuser
        self.assertTrue(self.admin.has_delete_permission(request, obj=self.post))

    def test_has_delete_permission_regular_user(self):
        request = self.factory.get("/admin/posts/post/")
        request.user = self.author
        self.assertFalse(self.admin.has_delete_permission(request, obj=self.post))

    def test_get_queryset_with_annotations(self):
        request = self.factory.get("/admin/posts/post/")
        request.user = self.superuser
        qs = self.admin.get_queryset(request)
        # Проверяем, что annotate применён
        self.assertIn("likes_count_annotated", qs.query.annotations)
        self.assertIn("comments_count_annotated", qs.query.annotations)

    def test_tags_list_empty(self):
        html = self.admin.tags_list(self.post)
        self.assertEqual(html, "-")

    def test_tags_list_with_tags(self):
        self.post.tags.add(Tag.objects.create(name="python"))
        html = self.admin.tags_list(self.post)
        self.assertIn("python", html)