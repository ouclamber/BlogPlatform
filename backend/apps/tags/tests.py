from django.contrib.auth import get_user_model
from rest_framework import status
from rest_framework.test import APITestCase

from .models import Tag

User = get_user_model()


class TagModelTests(APITestCase):
    def test_slug_autogenerated_from_name(self):
        tag = Tag.objects.create(name="Django")
        self.assertTrue(tag.slug)

    def test_str_returns_name(self):
        tag = Tag.objects.create(name="React")
        self.assertEqual(str(tag), "React")


class TagAPITests(APITestCase):
    def setUp(self):
        self.admin = User.objects.create_user(
            username="admin",
            email="admin@test.com",
            password="pass12345",
            role="admin",
        )
        self.reader = User.objects.create_user(
            username="reader",
            email="reader@test.com",
            password="pass12345",
            role="reader",
        )
        self.tag = Tag.objects.create(name="Python")

    def test_anyone_can_list_tags(self):
        response = self.client.get("/api/tags/")
        self.assertEqual(response.status_code, status.HTTP_200_OK)

    def test_anonymous_cannot_create_tag(self):
        response = self.client.post("/api/tags/", {"name": "JavaScript"})
        self.assertEqual(response.status_code, status.HTTP_401_UNAUTHORIZED)

    def test_authenticated_reader_can_create_tag(self):
        self.client.force_authenticate(self.reader)
        response = self.client.post("/api/tags/", {"name": "JavaScript"})
        self.assertEqual(response.status_code, status.HTTP_201_CREATED)

    def test_reader_cannot_edit_existing_tag(self):
        self.client.force_authenticate(self.reader)
        response = self.client.patch(
            f"/api/tags/{self.tag.slug}/", {"name": "Python3"}
        )
        self.assertEqual(response.status_code, status.HTTP_403_FORBIDDEN)

    def test_admin_can_edit_existing_tag(self):
        self.client.force_authenticate(self.admin)
        response = self.client.patch(
            f"/api/tags/{self.tag.slug}/", {"name": "Python3"}
        )
        self.assertEqual(response.status_code, status.HTTP_200_OK)

    def test_duplicate_name_case_insensitive_rejected(self):
        self.client.force_authenticate(self.reader)
        response = self.client.post("/api/tags/", {"name": "python"})
        self.assertEqual(response.status_code, status.HTTP_400_BAD_REQUEST)